package com.helger.phlox.api;

import org.jspecify.annotations.NonNull;
import org.jspecify.annotations.Nullable;

import com.helger.annotation.concurrent.Immutable;
import com.helger.base.enforce.ValueEnforcer;
import com.helger.phlox.api.model.PhloxInvoice;

/**
 * The descriptive properties of a rendered document - title, author, subject, keywords and the
 * generator - that the PDF writer puts into the document information and the HTML writer into the
 * meta elements of the page.
 *
 * @author Philip Helger
 */
@Immutable
public final class PhloxDocumentProperties
{
  /** The home page of the project. */
  public static final String PROJECT_URL = "https://github.com/phax/phlox";

  private PhloxDocumentProperties ()
  {}

  /**
   * Get the name of the application that created the document.
   *
   * @return <code>phlox</code> followed by the version. Never <code>null</code>.
   */
  @NonNull
  public static String getGenerator ()
  {
    return "phlox " + CPhloxVersion.BUILD_VERSION;
  }

  /**
   * Get the creator text of the document.
   *
   * @return A text like <code>Generated by phlox 1.0.0 - https://github.com/phax/phlox</code>.
   *         Never <code>null</code>.
   */
  @NonNull
  public static String getCreator ()
  {
    return "Generated by " + getGenerator () + " - " + PROJECT_URL;
  }

  /**
   * Get the localised name of the document kind.
   *
   * @param aInvoice
   *        The invoice to render. May not be <code>null</code>.
   * @param aCtx
   *        The render context for the language. May not be <code>null</code>.
   * @return The name, like "Invoice" or "Credit Note". Never <code>null</code>.
   */
  @NonNull
  public static String getKindName (@NonNull final PhloxInvoice aInvoice, @NonNull final AbstractRenderContext <?> aCtx)
  {
    ValueEnforcer.notNull (aInvoice, "Invoice");
    ValueEnforcer.notNull (aCtx, "Ctx");
    return aCtx.label (aInvoice.isCreditNote () ? "section.header.title.creditnote" : "section.header.title.invoice");
  }

  /**
   * Get the title of the document.
   *
   * @param aInvoice
   *        The invoice to render. May not be <code>null</code>.
   * @param aCtx
   *        The render context for the language. May not be <code>null</code>.
   * @return The kind and the number, like "Invoice: 12345". Never <code>null</code>.
   */
  @NonNull
  public static String getTitle (@NonNull final PhloxInvoice aInvoice, @NonNull final AbstractRenderContext <?> aCtx)
  {
    final String sKind = getKindName (aInvoice, aCtx);
    return aInvoice.getNumber () == null ? sKind : sKind + ": " + aInvoice.getNumber ();
  }

  /**
   * Get the author of the document.
   *
   * @param aInvoice
   *        The invoice to render. May not be <code>null</code>.
   * @return The name of the seller or <code>null</code> if there is none.
   */
  @Nullable
  public static String getAuthor (@NonNull final PhloxInvoice aInvoice)
  {
    ValueEnforcer.notNull (aInvoice, "Invoice");
    return aInvoice.getSeller () == null ? null : aInvoice.getSeller ().getName ();
  }

  /**
   * Get the subject of the document.
   *
   * @param aInvoice
   *        The invoice to render. May not be <code>null</code>.
   * @param aCtx
   *        The render context for the language. May not be <code>null</code>.
   * @return The standard, its edition and the kind, like "EN 16931:2026 Invoice". Never
   *         <code>null</code>.
   */
  @NonNull
  public static String getSubject (@NonNull final PhloxInvoice aInvoice, @NonNull final AbstractRenderContext <?> aCtx)
  {
    final String sEdition = aInvoice.getEdition () == null ? "" : ":" + aInvoice.getEdition ().name ().substring (2);
    return "EN 16931" + sEdition + " " + getKindName (aInvoice, aCtx);
  }

  /**
   * Get the keywords of the document.
   *
   * @param aInvoice
   *        The invoice to render. May not be <code>null</code>.
   * @param aCtx
   *        The render context for the language. May not be <code>null</code>.
   * @return The comma separated keywords. Never <code>null</code>.
   */
  @NonNull
  public static String getKeywords (@NonNull final PhloxInvoice aInvoice, @NonNull final AbstractRenderContext <?> aCtx)
  {
    return "EN 16931, " + getKindName (aInvoice, aCtx) + ", phlox";
  }
}
